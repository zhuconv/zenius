function joinCompositeString(parts, separator, collectElements) {
    let elements;
    if (collectElements) {
        elements = new Set();
        for (const part of parts) {
            for (const element of part.elements || [])
                elements.add(element);
        }
    }
    return { text: parts.map(part => part.text).join(separator), elements };
}
