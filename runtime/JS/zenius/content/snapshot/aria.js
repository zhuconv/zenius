function getElementAccessibleErrorMessage(element) {
    // SPEC: https://w3c.github.io/aria/#aria-errormessage
    //
    // TODO: support https://developer.mozilla.org/en-US/docs/Web/API/HTMLInputElement/validationMessage
    const cache = cacheAccessibleErrorMessage;
    let accessibleErrorMessage = cacheAccessibleErrorMessage?.get(element);
    if (accessibleErrorMessage === undefined) {
        accessibleErrorMessage = '';
        const isAriaInvalid = getAriaInvalid(element) !== 'false';
        const isValidityInvalid = getValidityInvalid(element);
        if (isAriaInvalid || isValidityInvalid) {
            const errorMessageId = $c_getAttribute(element, 'aria-errormessage');
            const errorMessages = getIdRefs(element, errorMessageId);
            // Ideally, this should be a separate "embeddedInErrorMessage", but it would follow the exact same rules.
            // Relevant vague spec: https://w3c.github.io/core-aam/#ariaErrorMessage.
            const parts = errorMessages.map(errorMessage => asFlatString(getTextAlternativeInternal(errorMessage, {
                visitedElements: new Set(),
                embeddedInDescribedBy: { element: errorMessage, hidden: isElementHiddenForAria(errorMessage) },
            }).text));
            accessibleErrorMessage = parts.join(' ').trim();
        }
        cache?.set(element, accessibleErrorMessage);
    }
    return accessibleErrorMessage;
}
function insideTargetElement(options) {
    return options.embeddedInTargetElement === 'self' || options.embeddedInTargetElement === 'descendant';
}
function getTextAlternativeInternal(element, options) {
    if (options.visitedElements.has(element))
        return emptyCompositeString();
    const childOptions = {
        ...options,
        embeddedInTargetElement: options.embeddedInTargetElement === 'self' ? 'descendant' : options.embeddedInTargetElement,
    };
    // step 2a. Hidden Not Referenced: If the current node is hidden and is:
    // Not part of an aria-labelledby or aria-describedby traversal, where the node directly referenced by that relation was hidden.
    // Nor part of a native host language text alternative element (e.g. label in HTML) or attribute traversal, where the root of that traversal was hidden.
    if (!options.includeHidden) {
        if (isElementIgnoredForAria(element) ||
            (!isEmbeddedInHiddenReferenceTraversal(options) && isElementHiddenForAria(element))) {
            options.visitedElements.add(element);
            return emptyCompositeString();
        }
    }
    const labelledBy = getAriaLabelledByElements(element);
    // step 2b. LabelledBy:
    // Otherwise, if the current node has an aria-labelledby attribute that contains
    // at least one valid IDREF, and the current node is not already part of an ongoing
    // aria-labelledby or aria-describedby traversal, process its IDREFs in the order they occur...
    if (!options.embeddedInLabelledBy) {
        const accessibleName = joinCompositeString((labelledBy || []).map(ref => getTextAlternativeInternal(ref, {
            ...options,
            embeddedInLabelledBy: { element: ref, hidden: isElementHiddenForAria(ref) },
            embeddedInDescribedBy: undefined,
            embeddedInTargetElement: undefined,
            embeddedInLabel: undefined,
            embeddedInNativeTextAlternative: undefined,
        })), ' ', options.collectElements);
        if (accessibleName.text) {
            if (options.outDerivedFromContent && insideTargetElement(options) && (labelledBy || []).some(ref => ref === element || $c_contains(element, ref)))
                options.outDerivedFromContent.value = true;
            return accessibleName;
        }
    }
    const role = getAriaRole(element) || '';
    const tagName = elementSafeTagName(element);
    // step 2c:
    //   if the current node is a control embedded within the label (e.g. any element directly referenced by aria-labelledby) for another widget...
    //
    // also step 2d "skip to rule Embedded Control" section:
    //   If traversal of the current node is due to recursion and the current node is an embedded control...
    // Note this is not strictly by the spec, because spec only applies this logic when "aria-label" is present.
    // However, browsers and and wpt test name_heading-combobox-focusable-alternative-manual.html follow this behavior,
    // and there is an issue filed for this: https://github.com/w3c/accname/issues/64
    if (!!options.embeddedInLabel || !!options.embeddedInLabelledBy || options.embeddedInTargetElement === 'descendant') {
        const isOwnLabel = [...$g_labels(element) || []].includes(element);
        const isOwnLabelledBy = (labelledBy || []).includes(element);
        if (!isOwnLabel && !isOwnLabelledBy) {
            // Searchbox is a subclass of textbox, so it is handled the same way.
            if (role === 'textbox' || role === 'searchbox') {
                options.visitedElements.add(element);
                if (tagName === 'INPUT' || tagName === 'TEXTAREA')
                    return compositeString(isSecretField(element) ? '' : $g_value(element), element, options.collectElements);
                return compositeString(isSecretField(element) ? '' : $g_textContent(element), element, options.collectElements);
            }
            if (['combobox', 'listbox'].includes(role)) {
                options.visitedElements.add(element);
                let selectedOptions;
                if (tagName === 'SELECT') {
                    selectedOptions = [...$g_selectedOptions(element)];
                    if (!selectedOptions.length && $g_length($g_options(element)))
                        selectedOptions.push($g_options(element)[0]);
                }
                else {
                    const listbox = role === 'combobox' ? queryInAriaOwned(element, '*').find(e => getAriaRole(e) === 'listbox') : element;
                    selectedOptions = listbox ? queryInAriaOwned(listbox, '[aria-selected="true" i]').filter(e => getAriaRole(e) === 'option') : [];
                }
                if (!selectedOptions.length && tagName === 'INPUT') {
                    // SPEC DIFFERENCE:
                    // This fallback is not explicitly mentioned in the spec, but all browsers and
                    // wpt test name_heading-combobox-focusable-alternative-manual.html do this.
                    return compositeString(isSecretField(element) ? '' : $g_value(element), element, options.collectElements);
                }
                return joinCompositeString(selectedOptions.map(option => getTextAlternativeInternal(option, childOptions)), ' ', options.collectElements);
            }
            if (['progressbar', 'scrollbar', 'slider', 'spinbutton', 'meter'].includes(role)) {
                options.visitedElements.add(element);
                if ($c_hasAttribute(element, 'aria-valuetext'))
                    return compositeString($c_getAttribute(element, 'aria-valuetext'), element, options.collectElements);
                if ($c_hasAttribute(element, 'aria-valuenow'))
                    return compositeString($c_getAttribute(element, 'aria-valuenow'), element, options.collectElements);
                return compositeString(isSecretField(element) ? '' : $c_getAttribute(element, 'value'), element, options.collectElements);
            }
            if (['menu'].includes(role)) {
                // https://github.com/w3c/accname/issues/67#issuecomment-553196887
                options.visitedElements.add(element);
                return emptyCompositeString();
            }
        }
    }
    // step 2d.
    const ariaLabel = $c_getAttribute(element, 'aria-label') || '';
    if (trimFlatString(ariaLabel)) {
        options.visitedElements.add(element);
        return compositeString(ariaLabel, element, options.collectElements);
    }
    // step 2e.
    if (!['presentation', 'none'].includes(role)) {
        if (!labelledBy && tagName.includes('-')) {
            const labels = getAssociatedLabels(element);
            if (labels.length) {
                options.visitedElements.add(element);
                return getAccessibleNameFromAssociatedLabels(labels, options);
            }
        }
        // https://w3c.github.io/html-aam/#input-type-button-input-type-submit-and-input-type-reset-accessible-name-computation
        //
        // SPEC DIFFERENCE.
        // Spec says to ignore this when aria-labelledby is defined.
        // WebKit follows the spec, while Chromium and Firefox do not.
        // We align with Chromium and Firefox here.
        if (tagName === 'INPUT' && ['button', 'submit', 'reset'].includes($g_type(element))) {
            options.visitedElements.add(element);
            const value = $g_value(element) || '';
            if (trimFlatString(value))
                return compositeString(value, element, options.collectElements);
            if ($g_type(element) === 'submit')
                return compositeString('Submit', element, options.collectElements);
            if ($g_type(element) === 'reset')
                return compositeString('Reset', element, options.collectElements);
            const title = $c_getAttribute(element, 'title') || '';
            return compositeString(title, element, options.collectElements);
        }
        // SPEC DIFFERENCE.
        // There is no spec for this, but Chromium/WebKit do "Choose File" so we follow that.
        // All browsers respect labels, aria-labelledby and aria-label.
        // No browsers respect the title attribute, although w3c accname tests disagree. We follow browsers.
        if (tagName === 'INPUT' && $g_type(element) === 'file') {
            options.visitedElements.add(element);
            const labels = $g_labels(element) || [];
            if ($g_length(labels) && !options.embeddedInLabelledBy)
                return getAccessibleNameFromAssociatedLabels(labels, options);
            return compositeString('Choose File', element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#input-type-image-accessible-name-computation
        //
        // SPEC DIFFERENCE.
        // Spec says to ignore this when aria-labelledby is defined, but all browsers take it into account.
        if (tagName === 'INPUT' && $g_type(element) === 'image') {
            options.visitedElements.add(element);
            const labels = $g_labels(element) || [];
            if ($g_length(labels) && !options.embeddedInLabelledBy)
                return getAccessibleNameFromAssociatedLabels(labels, options);
            const alt = $c_getAttribute(element, 'alt') || '';
            if (trimFlatString(alt))
                return compositeString(alt, element, options.collectElements);
            const title = $c_getAttribute(element, 'title') || '';
            if (trimFlatString(title))
                return compositeString(title, element, options.collectElements);
            // SPEC DIFFERENCE.
            // Spec says return localized "Submit Query", but browsers and axe-core insist on "Submit".
            return compositeString('Submit', element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#button-element-accessible-name-computation
        if (!labelledBy && tagName === 'BUTTON') {
            options.visitedElements.add(element);
            const labels = $g_labels(element) || [];
            if ($g_length(labels))
                return getAccessibleNameFromAssociatedLabels(labels, options);
            // From here, fallthrough to step 2f.
        }
        // https://w3c.github.io/html-aam/#output-element-accessible-name-computation
        if (!labelledBy && tagName === 'OUTPUT') {
            options.visitedElements.add(element);
            const labels = $g_labels(element) || [];
            if ($g_length(labels))
                return getAccessibleNameFromAssociatedLabels(labels, options);
            return compositeString($c_getAttribute(element, 'title') || '', element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#input-type-text-input-type-password-input-type-number-input-type-search-input-type-tel-input-type-email-input-type-url-and-textarea-element-accessible-name-computation
        // https://w3c.github.io/html-aam/#other-form-elements-accessible-name-computation
        // For "other form elements", we count select and any other input.
        //
        // Note: WebKit does not follow the spec and uses placeholder when aria-labelledby is present.
        if (!labelledBy && (tagName === 'TEXTAREA' || tagName === 'SELECT' || tagName === 'INPUT' || tagName === 'METER' || tagName === 'PROGRESS')) {
            options.visitedElements.add(element);
            const labels = $g_labels(element) || [];
            if ($g_length(labels))
                return getAccessibleNameFromAssociatedLabels(labels, options);
            const usePlaceholder = (tagName === 'INPUT' && ['text', 'password', 'number', 'search', 'tel', 'email', 'url'].includes($g_type(element))) || tagName === 'TEXTAREA';
            const placeholder = $c_getAttribute(element, 'placeholder') || '';
            const title = $c_getAttribute(element, 'title') || '';
            if (!usePlaceholder || title)
                return compositeString(title, element, options.collectElements);
            return compositeString(placeholder, element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#fieldset-and-legend-elements
        if (!labelledBy && tagName === 'FIELDSET') {
            options.visitedElements.add(element);
            for (let child = $g_firstElementChild(element); child; child = $g_nextElementSibling(child)) {
                if (elementSafeTagName(child) === 'LEGEND') {
                    return getTextAlternativeInternal(child, {
                        ...childOptions,
                        embeddedInNativeTextAlternative: { element: child, hidden: isElementHiddenForAria(child) },
                    });
                }
            }
            const title = $c_getAttribute(element, 'title') || '';
            return compositeString(title, element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#figure-and-figcaption-elements
        if (!labelledBy && tagName === 'FIGURE') {
            options.visitedElements.add(element);
            for (let child = $g_firstElementChild(element); child; child = $g_nextElementSibling(child)) {
                if (elementSafeTagName(child) === 'FIGCAPTION') {
                    return getTextAlternativeInternal(child, {
                        ...childOptions,
                        embeddedInNativeTextAlternative: { element: child, hidden: isElementHiddenForAria(child) },
                    });
                }
            }
            const title = $c_getAttribute(element, 'title') || '';
            return compositeString(title, element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#img-element
        //
        // SPEC DIFFERENCE.
        // Spec says to ignore this when aria-labelledby is defined, but all browsers take it into account.
        if (tagName === 'IMG') {
            options.visitedElements.add(element);
            const alt = $c_getAttribute(element, 'alt') || '';
            if (trimFlatString(alt))
                return compositeString(alt, element, options.collectElements);
            const title = $c_getAttribute(element, 'title') || '';
            return compositeString(title, element, options.collectElements);
        }
        // https://w3c.github.io/html-aam/#table-element
        if (tagName === 'TABLE') {
            options.visitedElements.add(element);
            for (let child = $g_firstElementChild(element); child; child = $g_nextElementSibling(child)) {
                if (elementSafeTagName(child) === 'CAPTION') {
                    return getTextAlternativeInternal(child, {
                        ...childOptions,
                        embeddedInNativeTextAlternative: { element: child, hidden: isElementHiddenForAria(child) },
                    });
                }
            }
            // SPEC DIFFERENCE.
            // Spec does not say a word about <table summary="...">, but all browsers actually support it.
            const summary = $c_getAttribute(element, 'summary') || '';
            if (summary)
                return compositeString(summary, element, options.collectElements);
            // SPEC DIFFERENCE.
            // Spec says "if the table element has a title attribute, then use that attribute".
            // We ignore title to pass "name_from_content-manual.html".
        }
        // https://w3c.github.io/html-aam/#area-element
        if (tagName === 'AREA') {
            options.visitedElements.add(element);
            const alt = $c_getAttribute(element, 'alt') || '';
            if (trimFlatString(alt))
                return compositeString(alt, element, options.collectElements);
            const title = $c_getAttribute(element, 'title') || '';
            return compositeString(title, element, options.collectElements);
        }
        // https://www.w3.org/TR/svg-aam-1.0/#mapping_additional_nd
        if (tagName === 'SVG' || $g_ownerSVGElement(element)) {
            options.visitedElements.add(element);
            for (let child = $g_firstElementChild(element); child; child = $g_nextElementSibling(child)) {
                if (elementSafeTagName(child) === 'TITLE' && $g_ownerSVGElement(child)) {
                    return getTextAlternativeInternal(child, {
                        ...childOptions,
                        embeddedInLabelledBy: { element: child, hidden: isElementHiddenForAria(child) },
                    });
                }
            }
        }
        if ($g_ownerSVGElement(element) && tagName === 'A') {
            const title = $c_getAttribute(element, 'xlink:title') || '';
            if (trimFlatString(title)) {
                options.visitedElements.add(element);
                return compositeString(title, element, options.collectElements);
            }
        }
    }
    // See https://w3c.github.io/html-aam/#summary-element-accessible-name-computation for "summary"-specific check.
    const shouldNameFromContentForSummary = tagName === 'SUMMARY' && !['presentation', 'none'].includes(role);
    // step 2f + step 2h.
    if (allowsNameFromContent(role, options.embeddedInTargetElement === 'descendant') ||
        shouldNameFromContentForSummary ||
        !!options.embeddedInLabelledBy || !!options.embeddedInDescribedBy ||
        !!options.embeddedInLabel || !!options.embeddedInNativeTextAlternative) {
        options.visitedElements.add(element);
        const accessibleName = innerAccumulatedElementText(element, childOptions);
        // Spec says "Return the accumulated text if it is not the empty string". However, that is not really
        // compatible with the real browser behavior and wpt tests, where an element with empty contents will fallback to the title.
        // So we follow the spec everywhere except for the target element itself. This can probably be improved.
        const maybeTrimmedAccessibleName = options.embeddedInTargetElement === 'self' ? trimFlatString(accessibleName.text) : accessibleName.text;
        if (maybeTrimmedAccessibleName) {
            if (options.outDerivedFromContent && insideTargetElement(options) && trimFlatString(accessibleName.text))
                options.outDerivedFromContent.value = true;
            // This element owns the accumulated content - record it alongside the descendants it was computed from.
            // Whitespace alone is not content, e.g. the spacing around an inline-block icon.
            if (trimFlatString(accessibleName.text))
                accessibleName.elements?.add(element);
            return accessibleName;
        }
    }
    // step 2i.
    if (!['presentation', 'none'].includes(role) || tagName === 'IFRAME' || tagName === 'FRAME') {
        options.visitedElements.add(element);
        const title = $c_getAttribute(element, 'title') || '';
        if (trimFlatString(title))
            return compositeString(title, element, options.collectElements);
    }
    options.visitedElements.add(element);
    return emptyCompositeString();
}
function isEmbeddedInHiddenReferenceTraversal(options) {
    return !!options.embeddedInLabelledBy?.hidden ||
        !!options.embeddedInDescribedBy?.hidden ||
        !!options.embeddedInNativeTextAlternative?.hidden ||
        !!options.embeddedInLabel?.hidden;
}
function innerAccumulatedElementText(element, options) {
    const tokens = [];
    // Similarly to step 2a, text nodes that are not rendered are skipped unless explicitly referenced.
    const skipNotRenderedText = !options.includeHidden && !isEmbeddedInHiddenReferenceTraversal(options);
    const elements = options.collectElements ? new Set() : undefined;
    const visit = (node, skipSlotted) => {
        if (skipSlotted && $g_assignedSlot(node))
            return;
        if ($g_nodeType(node) === 1 /* Node.ELEMENT_NODE */) {
            const display = $opt(getElementComputedStyle(node), $g_display) || 'inline';
            const childComposite = getTextAlternativeInternal(node, options);
            let token = childComposite.text;
            for (const contributor of childComposite.elements || [])
                elements?.add(contributor);
            // SPEC DIFFERENCE.
            // Spec says "append the result to the accumulated text", assuming "with space".
            // However, multiple tests insist that inline elements do not add a space.
            // Additionally, <br> insists on a space anyway, see "name_file-label-inline-block-elements-manual.html"
            if (display !== 'inline' || $g_nodeName(node) === 'BR')
                token = ' ' + token + ' ';
            tokens.push(token);
        }
        else if ($g_nodeType(node) === 3 /* Node.TEXT_NODE */) {
            if (skipNotRenderedText && isTextNodeNotRendered(node))
                return;
            // step 2g.
            tokens.push($g_textContent(node) || '');
        }
    };
    tokens.push(getCSSContent(element, '::before') || '');
    const content = getCSSContent(element);
    if (content !== undefined) {
        // `content` CSS property replaces everything inside the element.
        // I was not able to find any spec or description on how this interacts with accname,
        // so this is a guess based on what browsers do.
        tokens.push(content);
    }
    else {
        // step 2h.
        const assignedNodes = $g_nodeName(element) === 'SLOT' ? $c_assignedNodes(element) : [];
        if (assignedNodes.length) {
            for (const child of assignedNodes)
                visit(child, false);
        }
        else {
            for (let child = $g_firstChild(element); child; child = $g_nextSibling(child))
                visit(child, true);
            if ($g_shadowRoot(element)) {
                for (let child = $g_firstChild($g_shadowRoot(element)); child; child = $g_nextSibling(child))
                    visit(child, true);
            }
            for (const owned of getIdRefs(element, $c_getAttribute(element, 'aria-owns')))
                visit(owned, true);
        }
    }
    tokens.push(getCSSContent(element, '::after') || '');
    return { text: tokens.join(''), elements };
}
const kAriaSelectedRoles = ['gridcell', 'option', 'row', 'tab', 'rowheader', 'columnheader', 'treeitem'];
function getAriaSelected(element) {
    // https://www.w3.org/TR/wai-aria-1.2/#aria-selected
    // https://www.w3.org/TR/html-aam-1.0/#html-attribute-state-and-property-mappings
    if (elementSafeTagName(element) === 'OPTION')
        return $g_selected(element);
    if (kAriaSelectedRoles.includes(getAriaRole(element) || ''))
        return getAriaBoolean($c_getAttribute(element, 'aria-selected')) === true;
    return false;
}
const kAriaCheckedRoles = ['checkbox', 'menuitemcheckbox', 'option', 'radio', 'switch', 'menuitemradio', 'treeitem'];
function getAriaChecked(element) {
    const result = getChecked(element, true);
    return result === 'error' ? false : result;
}
function getCheckedAllowMixed(element) {
    return getChecked(element, true);
}
function getCheckedWithoutMixed(element) {
    const result = getChecked(element, false);
    return result;
}
function getChecked(element, allowMixed) {
    const tagName = elementSafeTagName(element);
    // https://www.w3.org/TR/wai-aria-1.2/#aria-checked
    // https://www.w3.org/TR/html-aam-1.0/#html-attribute-state-and-property-mappings
    if (allowMixed && tagName === 'INPUT' && $g_indeterminate(element))
        return 'mixed';
    if (tagName === 'INPUT' && ['checkbox', 'radio'].includes($g_type(element)))
        return $g_checked(element);
    if (kAriaCheckedRoles.includes(getAriaRole(element) || '')) {
        const checked = $c_getAttribute(element, 'aria-checked')?.toLowerCase();
        if (checked === 'true')
            return true;
        if (allowMixed && checked === 'mixed')
            return 'mixed';
        return false;
    }
    return 'error';
}
// https://w3c.github.io/aria/#aria-readonly
const kAriaReadonlyRoles = ['checkbox', 'combobox', 'grid', 'gridcell', 'listbox', 'radiogroup', 'slider', 'spinbutton', 'textbox', 'columnheader', 'rowheader', 'searchbox', 'switch', 'treegrid'];
function getReadonly(element) {
    const tagName = elementSafeTagName(element);
    // https://www.w3.org/TR/wai-aria-1.2/#aria-checked
    // https://www.w3.org/TR/html-aam-1.0/#html-attribute-state-and-property-mappings
    if (['INPUT', 'TEXTAREA', 'SELECT'].includes(tagName))
        return $c_hasAttribute(element, 'readonly');
    if (kAriaReadonlyRoles.includes(getAriaRole(element) || ''))
        return getAriaBoolean($c_getAttribute(element, 'aria-readonly')) === true;
    if ($g_isContentEditable(element))
        return false;
    return 'error';
}
const kAriaRequiredRoles = ['checkbox', 'combobox', 'gridcell', 'listbox', 'radiogroup', 'spinbutton', 'textbox', 'tree', 'columnheader', 'rowheader', 'searchbox', 'switch', 'treegrid'];
function getAriaRequired(element) {
    // https://www.w3.org/TR/wai-aria-1.2/#aria-required
    if (['INPUT', 'TEXTAREA', 'SELECT'].includes(elementSafeTagName(element)) && $c_hasAttribute(element, 'required'))
        return true;
    if (kAriaRequiredRoles.includes(getAriaRole(element) || ''))
        return getAriaBoolean($c_getAttribute(element, 'aria-required')) === true;
    return false;
}
const kAriaPressedRoles = ['button'];
function getAriaPressed(element) {
    // https://www.w3.org/TR/wai-aria-1.2/#aria-pressed
    if (kAriaPressedRoles.includes(getAriaRole(element) || '')) {
        const pressed = $c_getAttribute(element, 'aria-pressed')?.toLowerCase();
        if (pressed === 'true')
            return true;
        if (pressed === 'mixed')
            return 'mixed';
    }
    return false;
}
const kAriaExpandedRoles = ['application', 'button', 'checkbox', 'combobox', 'gridcell', 'link', 'listbox', 'menuitem', 'row', 'rowheader', 'tab', 'treeitem', 'columnheader', 'menuitemcheckbox', 'menuitemradio', 'rowheader', 'switch'];
function getAriaExpanded(element) {
    // https://www.w3.org/TR/wai-aria-1.2/#aria-expanded
    // https://www.w3.org/TR/html-aam-1.0/#html-attribute-state-and-property-mappings
    if (elementSafeTagName(element) === 'DETAILS')
        return $g_open(element);
    if (kAriaExpandedRoles.includes(getAriaRole(element) || ''))
        return getAriaBoolean($c_getAttribute(element, 'aria-expanded'));
    return undefined;
}
const kAriaLevelRoles = ['heading', 'listitem', 'row', 'treeitem'];
function getAriaLevel(element) {
    // https://www.w3.org/TR/wai-aria-1.2/#aria-level
    // https://www.w3.org/TR/html-aam-1.0/#html-attribute-state-and-property-mappings
    const native = { 'H1': 1, 'H2': 2, 'H3': 3, 'H4': 4, 'H5': 5, 'H6': 6 }[elementSafeTagName(element)];
    if (native)
        return native;
    if (kAriaLevelRoles.includes(getAriaRole(element) || '')) {
        const attr = $c_getAttribute(element, 'aria-level');
        const value = attr === null ? Number.NaN : Number(attr);
        if (Number.isInteger(value) && value >= 1)
            return value;
    }
    return 0;
}
const kAriaDisabledRoles = ['application', 'button', 'composite', 'gridcell', 'group', 'input', 'link', 'menuitem', 'scrollbar', 'separator', 'tab', 'checkbox', 'columnheader', 'combobox', 'grid', 'listbox', 'menu', 'menubar', 'menuitemcheckbox', 'menuitemradio', 'option', 'radio', 'radiogroup', 'row', 'rowheader', 'searchbox', 'select', 'slider', 'spinbutton', 'switch', 'tablist', 'textbox', 'toolbar', 'tree', 'treegrid', 'treeitem'];
function getAriaDisabled(element) {
    // https://www.w3.org/TR/wai-aria-1.2/#aria-disabled
    // Note that aria-disabled applies to all descendants, so we look up the hierarchy.
    return isNativelyDisabled(element) || hasExplicitAriaDisabled(element);
}
function isNativelyDisabled(element) {
    // https://www.w3.org/TR/html-aam-1.0/#html-attribute-state-and-property-mappings
    const isNativeFormControl = ['BUTTON', 'INPUT', 'SELECT', 'TEXTAREA', 'OPTION', 'OPTGROUP'].includes(elementSafeTagName(element));
    return isNativeFormControl && ($c_hasAttribute(element, 'disabled') || belongsToDisabledOptGroup(element) || belongsToDisabledFieldSet(element));
}
function belongsToDisabledOptGroup(element) {
    return elementSafeTagName(element) === 'OPTION' && !!$c_closest(element, 'OPTGROUP[DISABLED]');
}
function belongsToDisabledFieldSet(element) {
    const fieldSetElement = $optCall(element, $c_closest, 'FIELDSET[DISABLED]');
    if (!fieldSetElement)
        return false;
    const legendElement = $c_querySelector(fieldSetElement, ':scope > LEGEND');
    return !legendElement || !$c_contains(legendElement, element);
}
function hasExplicitAriaDisabled(element) {
    if (!kAriaDisabledRoles.includes(getAriaRole(element) || ''))
        return false;
    return hasAriaDisabledInChain(element);
}
function hasAriaDisabledInChain(element) {
    let result = cacheAriaDisabled?.get(element);
    if (result === undefined) {
        const attribute = ($c_getAttribute(element, 'aria-disabled') || '').toLowerCase();
        if (attribute === 'true') {
            result = true;
        }
        else if (attribute === 'false') {
            result = false;
        }
        else {
            // aria-disabled works across shadow boundaries.
            const parent = parentElementOrShadowHost(element);
            result = parent ? hasAriaDisabledInChain(parent) : false;
        }
        cacheAriaDisabled?.set(element, result);
    }
    return result;
}
function getAccessibleNameFromAssociatedLabels(labels, options) {
    return joinCompositeString([...labels].map(label => getTextAlternativeInternal(label, {
        ...options,
        embeddedInLabel: { element: label, hidden: isElementHiddenForAria(label) },
        embeddedInNativeTextAlternative: undefined,
        embeddedInLabelledBy: undefined,
        embeddedInDescribedBy: undefined,
        embeddedInTargetElement: undefined,
    })).filter(accessibleName => !!accessibleName.text), ' ', options.collectElements);
}
function receivesPointerEvents(element) {
    const cache = cachePointerEvents;
    let e = element;
    let result;
    const parents = [];
    for (; e; e = parentElementOrShadowHost(e)) {
        const cached = cache.get(e);
        if (cached !== undefined) {
            result = cached;
            break;
        }
        parents.push(e);
        const style = getElementComputedStyle(e);
        if (!style) {
            result = true;
            break;
        }
        const value = $g_pointerEvents(style);
        if (value) {
            result = value !== 'none';
            break;
        }
    }
    if (result === undefined)
        result = true;
    for (const parent of parents)
        cache.set(parent, result);
    return result;
}
